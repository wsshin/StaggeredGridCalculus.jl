# Assumes the space dimension and field dimension are the same.  In other words, when the
# space coordinate indices are (i,j,k), then the field has three vector components.
# Therefore, for the output field array G[i,j,k,w], we assume w = 1:3.

# The functions add the calculated values to the existing values of the output array.
# Therefore, if the derivative values themselves are desired, pass the output array
# initialized with zeros.

export apply_grad!

# Wrapper to apply the discrete gradient by default
#
# Note that when the positional arguments are SVector's, this function may call the concrete
# implementation directly instead of the next wrapper function taking ∆l⁻¹ even if the
# keyword arguments are not SVector's, because methods are dispatched based only on the
# types of positional arguments.  Therefore, we convert the keyword arguments into SVector's.
apply_grad!(
    G::AbstractArray{<:Number},  # output field; in 3D, G[i,j,k,w] is w-component of G at (i,j,k)
    fv̲F::AbstractArray{<:Number},  # input array of scalar; in 3D, f[i,j,k] is f at (i,j,k)
    isfwd::AbstractVector{Bool},  # isfwd[w] = true|false: ∂w is forward|backward difference
    ∆l⁻¹::NTuple{K,Number}=ntuple(x->1,length(isfwd)),  # ∆l⁻¹[w]: inverse of uniform distance (not distances) between grid planes in w-direction
    isbloch::AbstractVector{Bool}=ones(Bool,K),  # isbloch[w]: boundary condition in w-direction
    e⁻ⁱᵏᴸ::AbstractVector{<:Number}=ones(Int,K);  # e⁻ⁱᵏᴸ[w]: Bloch phase factor in w-direction
    kwargs...
) where {K} =
    (N = size(G)[1:K]; apply_grad!(G, fv̲F, isfwd, fill.(∆l⁻¹,N), isbloch, e⁻ⁱᵏᴸ; kwargs...))

# Wrapper for converting AbstractVector's to SVector's
apply_grad!(
    G::AbstractArray{<:Number},  # output field; in 3D, G[i,j,k,w] is w-component of G at (i,j,k)
    fv̲F::AbstractArray{<:Number},  # input array of scalar; in 3D, f[i,j,k] is f at (i,j,k)
    isfwd::AbstractVector{Bool},  # isfwd[w] = true|false: ∂w is forward|backward difference
    ∆l⁻¹::NTuple{K,AbstractVector{<:Number}},  # ∆l⁻¹[w]: inverse of distances between grid planes in w-direction
    isbloch::AbstractVector{Bool}=ones(Bool,K),  # isbloch[w]: boundary condition in w-direction
    e⁻ⁱᵏᴸ::AbstractVector{<:Number}=ones(Int,K);  # e⁻ⁱᵏᴸ[w]: Bloch phase factor in w-direction
    kwargs...
) where {K} =
    apply_grad!(G, fv̲F, SVector{K,Bool}(isfwd), ∆l⁻¹, SVector{K,Bool}(isbloch), SVector{K}(e⁻ⁱᵏᴸ); kwargs...)

# Concrete implementation
function apply_grad!(
    G::AbstractArray{<:Number,K₊₁},  # output field; in 3D, G[i,j,k,w] is w-component of G at (i,j,k)
    f::AbstractArray{<:Number,K},  # input array of scalar; in 3D, f[i,j,k] is f at (i,j,k)
    isfwd::SVector{K,Bool},  # isfwd[w] = true|false: create ∂w by forward|backward difference
    ∆l⁻¹::NTuple{K,AbstractVector{<:Number}},  # ∆l[w]: inverse of distances between grid planes in x-direction
    isbloch::SVector{K,Bool},  # isbloch[w]: boundary condition in w-direction
    e⁻ⁱᵏᴸ::SVector{K,<:Number};  # e⁻ⁱᵏᴸ[w]: Bloch phase factor in w-direction
    cmp_out=1:K,  # integer or vector of integers in 1:K; output components into which gradient is taken; can be used to, e.g., calculating 2D gradient in 3D space; does not change number of rows (output remains K-dimensional)
    α::Number=1,  # scale factor to multiply to result before adding it to g: g += α ∇⋅F
    overwrite::Bool=true  # false to add result to output storage G
) where {K,K₊₁}
    @assert K₊₁==K+1
    @argcheck allunique(cmp_out)

    for nw = cmp_out  # direction of differentiation
        nv = nw  # component of output field generated by ∂w (index of matrix block)
        Gᵥ = selectdim(G, K₊₁, nv)  # nv-th component of output field
        apply_∂!(Gᵥ, f, nw, isfwd[nw], ∆l⁻¹[nw], isbloch[nw], e⁻ⁱᵏᴸ[nw]; α, overwrite) # Gᵥ += α ∂f/∂w
    end

    return nothing
end

# Concrete implementation for a vector field input.
# This is not necessary because we can simply pass f = @view(G[:,:,:,cmp_in]) to apply_grad!(),
# but it is implemented to be aligned with create_grad().
apply_grad!(
    G::AbstractArray{<:Number,K₊₁},  # output field; in 3D, G[i,j,k,w] is w-component of G at (i,j,k)
    F::AbstractArray{<:Number,K₊₁},  # input array of scalar; in 3D, f[i,j,k] is f at (i,j,k)
    isfwd::SVector{K,Bool},  # isfwd[w] = true|false: create ∂w by forward|backward difference
    ∆l⁻¹::NTuple{K,AbstractVector{<:Number}},  # ∆l[w]: inverse of distances between grid planes in x-direction
    isbloch::SVector{K,Bool},  # isbloch[w]: boundary condition in w-direction
    e⁻ⁱᵏᴸ::SVector{K,<:Number};  # e⁻ⁱᵏᴸ[w]: Bloch phase factor in w-direction
    cmp_in::Integer,  # creates square matrix acting on cmp_in-th Cartesian direction of input vector field
    kwargs...
) where {K,K₊₁} = (
    f = @view(F[:,:,:,cmp_in]);
    apply_grad!(G, f, isfwd, ∆l⁻¹, isbloch, e⁻ⁱᵏᴸ; kwargs...)
)
